#!/usr/bin/env python3
"""
Replay daily-min-sc10 on historical MCX CRUDEOILM 5-minute candles.

This is the tape, not a live lock. The guaranteed-profit gate still fails
if any full-session day is red or flat after ₹50/RT.

  python3 scripts/crude-historical-candle-replay.py
"""
from __future__ import annotations

import importlib.util
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "crude-historical-candles"
OUT.mkdir(parents=True, exist_ok=True)
TS = (
    ROOT
    / "src"
    / "app"
    / "core"
    / "strategy-engine"
    / "strategies"
    / "crude-daily-green"
    / "crude-historical-candles.fixture.ts"
)
JSON_OUT = (
    ROOT
    / "src"
    / "app"
    / "core"
    / "strategy-engine"
    / "strategies"
    / "crude-daily-green"
    / "crude-historical-candles.fixture.json"
)

spec = importlib.util.spec_from_file_location("cdm", ROOT / "scripts" / "crude-daily-min-hunt.py")
mod = importlib.util.module_from_spec(spec)
assert spec.loader
spec.loader.exec_module(mod)

WIRED = dict(
    mode="all_three",
    tp=25,
    scratch=10,
    against_close=True,
    first_win=True,
    day_lock=20,
    week_lock=0,
    max_day=2,
    entry_s=10 * 60,
    entry_e=23 * 60,
)


def main():
    mk = mod.load()
    trades = mod.simulate(mk, **WIRED)
    tradable = [d for d in mk["uniq"] if mk["kind"].get(d) not in (None, "thin")]
    by = defaultdict(list)
    for t in trades:
        by[t["day"]].append(t)

    days = []
    for d in tradable:
        rows = by.get(d, [])
        rs = sum(t["rs"] for t in rows)
        tone = "green" if rs > 0 else "red" if rs < 0 else "flat"
        days.append(
            {
                "day": d,
                "kind": mk["kind"][d],
                "rs": round(rs, 1),
                "trades": len(rows),
                "tone": tone,
                "hit150": rs >= 150,
                "exits": [t["reason"] for t in rows],
            }
        )

    green = sum(1 for r in days if r["tone"] == "green")
    red = sum(1 for r in days if r["tone"] == "red")
    flat = sum(1 for r in days if r["tone"] == "flat")
    hit150 = sum(1 for r in days if r["hit150"])
    nets = [r["rs"] for r in days]
    weeks = defaultdict(float)
    for r in days:
        weeks[mod.week_monday(r["day"])] += r["rs"]
    wnets = list(weeks.values())

    tape = {
        "instrument": "CRUDEOILM FUT",
        "profileId": "daily-min-sc10",
        "sample": "MCX CRUDEOILM 5m 2026-05-21 → 2026-10-30",
        "bars": int(mk["n"]),
        "calendarDays": len(mk["uniq"]),
        "tradableDays": len(days),
        "thinDays": len(mk["uniq"]) - len(days),
        "chargesRs": 50,
        "rupeesPerPoint": 10,
        "greenDays": green,
        "redDays": red,
        "flatDays": flat,
        "hit150": hit150,
        "netRs": round(sum(nets), 1),
        "avgDayRs": round(sum(nets) / len(nets), 1) if nets else 0,
        "worstDayRs": round(min(nets), 1) if nets else 0,
        "bestDayRs": round(max(nets), 1) if nets else 0,
        "greenWeeks": sum(1 for v in wnets if v > 0),
        "weeks": len(wnets),
        "worstWeekRs": round(min(wnets), 1) if wnets else 0,
        "everyDayGreen": red == 0 and flat == 0 and len(days) > 0,
        "everyDay150": hit150 == len(days) and len(days) > 0,
        "guaranteed": False,
        "honest": (
            "Historical 5-minute replay of daily-min-sc10. "
            "Not a guaranteed profit. Red and flat days remain on the tape."
        ),
        "days": days,
    }
    JSON_OUT.write_text(json.dumps(tape, indent=2) + "\n")
    OUT.joinpath("summary.json").write_text(json.dumps(tape, indent=2))

    ts = [
        "/** Historical 5-minute replay of daily-min-sc10. Generated by",
        " *  scripts/crude-historical-candle-replay.py. Not a live lock.",
        " */",
        "export const CRUDE_HISTORICAL_CANDLES = "
        + json.dumps(tape, indent=2)
        + " as const;",
        "",
    ]
    TS.write_text("\n".join(ts).replace("true", "true").replace("false", "false"))

    lines = [
        f"bars {tape['bars']}  calendar {tape['calendarDays']}  tradable {tape['tradableDays']}  thin {tape['thinDays']}",
        f"green {green}  red {red}  flat {flat}  hit150 {hit150}/{len(days)}",
        f"net ₹{tape['netRs']:.0f}  avg ₹{tape['avgDayRs']:.0f}  worst ₹{tape['worstDayRs']:.0f}  best ₹{tape['bestDayRs']:.0f}",
        f"weeks {tape['greenWeeks']}/{tape['weeks']} green  worst week ₹{tape['worstWeekRs']:.0f}",
        f"everyDayGreen {tape['everyDayGreen']}  everyDay150 {tape['everyDay150']}  guaranteed {tape['guaranteed']}",
        tape["honest"],
        "",
        f"{'day':<12} {'kind':<9} {'₹':>7} {'n':>2} exits",
    ]
    for r in days:
        lines.append(
            f"{r['day']:<12} {r['kind']:<9} {r['rs']:7.0f} {r['trades']:2d} {','.join(r['exits']) or '—'}"
        )
    report = "\n".join(lines) + "\n"
    OUT.joinpath("README.md").write_text("# Crude historical 5m candle replay\n\n```\n" + report + "```\n")
    print(report, flush=True)


if __name__ == "__main__":
    main()
